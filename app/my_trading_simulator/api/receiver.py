
"""
Authenticated notification receiver for my-trading-simulator.

Accepts notifications from iPhone Shortcuts and manual input.
Stores messages in the existing SQLite database.

This API does NOT execute paper or live trades.
"""

import hmac
import os
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Literal

from dotenv import load_dotenv
from fastapi import FastAPI, Header, HTTPException
from pydantic import BaseModel, Field, field_validator
from sqlalchemy import select
from sqlalchemy.exc import IntegrityError

from my_trading_simulator.database.models import IncomingNotification
from my_trading_simulator.database.session import SessionLocal
from my_trading_simulator.ingestion.duplicate_detector import normalize_message


PROJECT_ROOT = Path(__file__).resolve().parents[3]
load_dotenv(dotenv_path=PROJECT_ROOT / ".env")

API_TOKEN = os.getenv("NOTIFICATION_API_TOKEN", "")

if len(API_TOKEN) < 32:
    raise RuntimeError(
        "NOTIFICATION_API_TOKEN must be configured "
        "with at least 32 characters."
    )

DUPLICATE_WINDOW_SECONDS = 60

app = FastAPI(
    title="My Trading Simulator Notification Receiver",
    docs_url=None,
    redoc_url=None,
    openapi_url=None,
)


class NotificationRequest(BaseModel):
    source: Literal[
        "IPHONE_NOTIFICATION",
        "MANUAL_DISCORD",
        "MANUAL_ENTRY",
    ]

    message_text: str = Field(
        min_length=1,
        max_length=4000,
    )

    idempotency_key: str = Field(
        min_length=8,
        max_length=64,
        pattern=r"^[A-Za-z0-9_-]+$",
    )

    source_message_id: str | None = Field(
        default=None,
        max_length=100,
    )

    source_timestamp: datetime | None = None

    @field_validator("message_text")
    @classmethod
    def validate_message(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("Message cannot be blank")
        return value

    @field_validator("source_timestamp")
    @classmethod
    def validate_timestamp(cls, value: datetime | None):
        if value is not None:
            if value.tzinfo is None or value.utcoffset() is None:
                raise ValueError(
                    "source_timestamp must include a timezone"
                )
        return value


class NotificationResponse(BaseModel):
    status: str
    notification_id: int
    duplicate: bool


def verify_token(authorization: str | None) -> None:
    """Reject requests without the correct bearer token."""

    prefix = "Bearer "

    if not authorization or not authorization.startswith(prefix):
        raise HTTPException(
            status_code=401,
            detail="Unauthorized",
        )

    provided_token = authorization[len(prefix):]

    if not hmac.compare_digest(provided_token, API_TOKEN):
        raise HTTPException(
            status_code=401,
            detail="Unauthorized",
        )


def utc_timestamp(value: datetime | None) -> datetime | None:
    """
    Convert timestamps to timezone-aware UTC.

    SQLite can return datetime values without timezone information.
    Timestamps generated by this application are stored as UTC.
    """

    if value is None:
        return None

    if value.tzinfo is None:
        return value.replace(tzinfo=timezone.utc)

    return value.astimezone(timezone.utc)


def existing_response(
    existing: IncomingNotification,
    request: NotificationRequest,
) -> NotificationResponse:
    """
    Handle a repeated idempotency key.

    Identical request -> DUPLICATE
    Different request -> HTTP 409
    """

    if (
        existing.source != request.source
        or existing.message_text != request.message_text
        or existing.source_message_id != request.source_message_id
        or utc_timestamp(existing.source_timestamp)
        != utc_timestamp(request.source_timestamp)
    ):
        raise HTTPException(
            status_code=409,
            detail="Idempotency key already used for different content",
        )

    return NotificationResponse(
        status="DUPLICATE",
        notification_id=existing.id,
        duplicate=True,
    )

def is_possible_duplicate(
    *,
    session,
    message_text: str,
    received_at: datetime,
) -> bool:
    """
    Find possible duplicate notifications received within 60 seconds.

    Uses the indexed received_at column instead of scanning
    the latest 500 records.

    All application-generated received_at timestamps are UTC.
    SQLite stores them without timezone information.
    """

    # Convert UTC timestamps to SQLite-compatible naive UTC.
    received_at_utc = received_at.astimezone(
        timezone.utc
    ).replace(tzinfo=None)

    window_start = received_at_utc - timedelta(
        seconds=DUPLICATE_WINDOW_SECONDS
    )

    # Indexed query: fetch only notifications in the time window.
    recent = session.scalars(
        select(IncomingNotification).where(
            IncomingNotification.received_at >= window_start,
            IncomingNotification.received_at <= received_at_utc,
        )
    ).all()

    incoming_normalized = normalize_message(message_text)

    for previous in recent:
        previous_time = utc_timestamp(previous.received_at)

        if previous_time is None:
            continue

        age_seconds = (
            received_at - previous_time
        ).total_seconds()

        if not 0 <= age_seconds <= DUPLICATE_WINDOW_SECONDS:
            continue

        if (
            incoming_normalized
            == normalize_message(previous.message_text)
        ):
            return True

    return False

@app.post(
    "/api/v1/notifications",
    response_model=NotificationResponse,
)
def receive_notification(
    request: NotificationRequest,
    authorization: str | None = Header(default=None),
):
    """
    Authenticated notification ingestion.

    Steps:
      1. Authenticate.
      2. Begin SQLite write transaction.
      3. Check request idempotency.
      4. Check for possible cross-source duplicates.
      5. Save incoming notification.
      6. Return status.

    No trades are executed.
    """

    verify_token(authorization)

    received_at = datetime.now(timezone.utc)

    with SessionLocal() as session:
        # Serialize concurrent SQLite inbox writes.
        session.connection().exec_driver_sql("BEGIN IMMEDIATE")

        existing = session.scalar(
            select(IncomingNotification).where(
                IncomingNotification.idempotency_key
                == request.idempotency_key
            )
        )

        if existing is not None:
            response = existing_response(existing, request)
            session.rollback()
            return response

        possible_duplicate = is_possible_duplicate(
            session=session,
            message_text=request.message_text,
            received_at=received_at,
        )

        processing_status = (
            "POSSIBLE_DUPLICATE"
            if possible_duplicate
            else "RECEIVED"
        )

        notification = IncomingNotification(
            source=request.source,
            source_message_id=request.source_message_id,
            idempotency_key=request.idempotency_key,
            message_text=request.message_text,
            source_timestamp=request.source_timestamp,
            received_at=received_at,
            processing_status=processing_status,
        )

        session.add(notification)

        try:
            session.commit()

        except IntegrityError:
            session.rollback()

            existing = session.scalar(
                select(IncomingNotification).where(
                    IncomingNotification.idempotency_key
                    == request.idempotency_key
                )
            )

            if existing is not None:
                return existing_response(existing, request)

            raise HTTPException(
                status_code=409,
                detail="Notification could not be inserted",
            )

        return NotificationResponse(
            status=processing_status,
            notification_id=notification.id,
            duplicate=possible_duplicate,
        )


@app.get("/health")
def health():
    """Basic API health check."""
    return {"status": "ok"}
